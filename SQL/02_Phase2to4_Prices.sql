FROM O_ECON.COMMON.HPT_P4_HOSPITAL_CONCEPT_PRICES C
INNER JOIN O_ECON.COMMON.HPT_P4_HOSPITAL_POSTING_CONTEXT H ON C.HOSPITAL_ID = H.HOSPITAL_ID;

