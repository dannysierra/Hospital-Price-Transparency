FROM O_ECON.COMMON.HPT_P3_HOSPITAL_EXACT_CODE_PRICES E
INNER JOIN O_ECON.COMMON.HPT_P4_HOSPITAL_POSTING_CONTEXT H ON E.HOSPITAL_ID = H.HOSPITAL_ID
